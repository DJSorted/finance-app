// Writes version.js: one hash of every file the site serves.
// sw.js imports it, so any change to the app changes the service worker's
// bytes; the browser then installs the new worker and pwa.js shows the
// "New version available" bar.
//
// Runs automatically on `npx wrangler deploy` (wrangler.jsonc build.command).
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT  = path.resolve(__dirname, '..');
const FILES = ['index.html', '404.html', 'sw.js', 'manifest.webmanifest', '_headers'];
const DIRS  = ['css', 'js', 'pages', 'icons', 'assets'];
const OUT   = path.join(ROOT, 'version.js');

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

const all = [...FILES.map((f) => path.join(ROOT, f)), ...DIRS.flatMap((d) => walk(path.join(ROOT, d)))]
  .filter((f) => fs.existsSync(f))
  .sort();

const h = crypto.createHash('sha1');
for (const f of all) {
  h.update(path.relative(ROOT, f).split(path.sep).join('/'));
  h.update(fs.readFileSync(f));
}
const version = h.digest('hex').slice(0, 12);

fs.writeFileSync(OUT, `// Generated by scripts/build-version.js on deploy. Do not edit.\nself.APP_VERSION = '${version}';\n`);
console.log(`version.js: ${all.length} files, version ${version}`);
